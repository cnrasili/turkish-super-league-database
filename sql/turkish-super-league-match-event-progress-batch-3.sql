DECLARE @MatchMap TABLE (
    source_match_id INT NOT NULL PRIMARY KEY,
    match_id INT NOT NULL UNIQUE
);

INSERT INTO @MatchMap (source_match_id, match_id)
SELECT input.source_match_id, match_row.match_id
FROM @MatchInput AS input
INNER JOIN dbo.season AS season ON season.name = N'2025-2026'
INNER JOIN dbo.[match] AS match_row
    ON match_row.season_id = season.season_id AND match_row.week = input.week
INNER JOIN dbo.club AS home_club
    ON home_club.club_id = match_row.home_club_id AND home_club.name = input.home_club_name
INNER JOIN dbo.club AS away_club
    ON away_club.club_id = match_row.away_club_id AND away_club.name = input.away_club_name;

IF (SELECT COUNT(*) FROM @MatchMap) <> 20
    THROW 51310, 'Each selected source fixture must resolve to exactly one match row.', 1;

IF EXISTS (
    SELECT 1 FROM @AppearanceInput AS input
    LEFT JOIN dbo.person AS person ON person.name = input.player_name
    LEFT JOIN dbo.player AS player ON player.person_id = person.person_id
    WHERE player.person_id IS NULL
)
    THROW 51311, 'Every appearance participant must resolve to a player profile.', 1;

IF EXISTS (
    SELECT 1 FROM @EventInput AS input
    LEFT JOIN dbo.person AS person ON person.name = input.player_name
    LEFT JOIN dbo.player AS player ON player.person_id = person.person_id
    WHERE player.person_id IS NULL
)
    THROW 51312, 'Every event participant must resolve to a player profile.', 1;

IF EXISTS (
    SELECT 1 FROM @MatchMap AS match_map
    WHERE EXISTS (SELECT 1 FROM dbo.appearance WHERE match_id = match_map.match_id)
       OR EXISTS (SELECT 1 FROM dbo.match_event WHERE match_id = match_map.match_id)
)
    THROW 51313, 'A selected fixture already has appearance or event rows.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    INSERT INTO dbo.appearance (match_id, player_id, is_starter)
    SELECT match_map.match_id, player.person_id, input.is_starter
    FROM @AppearanceInput AS input
    INNER JOIN @MatchMap AS match_map ON match_map.source_match_id = input.source_match_id
    INNER JOIN dbo.person AS person ON person.name = input.player_name
    INNER JOIN dbo.player AS player ON player.person_id = person.person_id;

    INSERT INTO dbo.match_event (match_id, event_no, minute)
    SELECT match_map.match_id, input.event_no, input.minute
    FROM @EventInput AS input
    INNER JOIN @MatchMap AS match_map ON match_map.source_match_id = input.source_match_id;

    INSERT INTO dbo.event_player (match_id, event_no, player_id, [role])
    SELECT match_map.match_id, input.event_no, player.person_id, input.player_role
    FROM @EventInput AS input
    INNER JOIN @MatchMap AS match_map ON match_map.source_match_id = input.source_match_id
    INNER JOIN dbo.person AS person ON person.name = input.player_name
    INNER JOIN dbo.player AS player ON player.person_id = person.person_id;

    INSERT INTO dbo.goal (match_id, event_no, goal_type)
    SELECT match_map.match_id, input.event_no, input.goal_type
    FROM @EventInput AS input
    INNER JOIN @MatchMap AS match_map ON match_map.source_match_id = input.source_match_id
    WHERE input.event_type = N'goal';

    INSERT INTO dbo.card (match_id, event_no, colour)
    SELECT match_map.match_id, input.event_no, input.card_colour
    FROM @EventInput AS input
    INNER JOIN @MatchMap AS match_map ON match_map.source_match_id = input.source_match_id
    WHERE input.event_type = N'card';

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
